// ── Login rate limiting (failed attempts only) ────────────────────────────

async function login_rate_limited(env, auth_code) {
  // Prune first, then check — same pattern as activation rate limiting.
  const now = Math.floor(Date.now() / 1000);
  await env.DB.prepare('DELETE FROM rate_events WHERE ts < ?1')
    .bind(now - LOGIN_WINDOW_S)
    .run();
  const bucket = `login:${auth_code.slice(0, 24)}`;
  const { results } = await env.DB.prepare(
    'SELECT COUNT(*) AS n FROM rate_events WHERE bucket = ?1 AND ts >= ?2',
  )
    .bind(bucket, now - LOGIN_WINDOW_S)
    .all();
  return (results?.[0]?.n ?? 0) >= LOGIN_RATE;
}

async function record_login_failure(env, auth_code) {
  const bucket = `login:${auth_code.slice(0, 24)}`;
  await env.DB.prepare(
    'INSERT INTO rate_events (bucket, ts) VALUES (?1, ?2)',
  )
    .bind(bucket, Math.floor(Date.now() / 1000))
    .run();
}

// ── Shared helpers ────────────────────────────────────────────────────────

// SHA-256 over raw bytes → hex (used by the pretty-key codec).
async function sha256_hex_bytes(bytes) {
  const digest = await crypto.subtle.digest('SHA-256', bytes);
  return [...new Uint8Array(digest)]
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('');
}

// Re-exported store-bridge helpers used by admin handlers.
import { normalize_store_key, key_hint } from './store-bridge.js';

async function sha256_hex(s) {
  const digest = await crypto.subtle.digest(
    'SHA-256',
    new TextEncoder().encode(s),
  );
  return [...new Uint8Array(digest)]
    .map((b) => b.toString(16).padStart(2, '0'))
    .join('');
}

function now_iso(ms = Date.now()) {
  return new Date(ms).toISOString().replace(/\.\d{3}Z$/, 'Z');
}

// ── Rate limiting ─────────────────────────────────────────────────────────

async function rate_limit(db, machine_id) {
  const now = Math.floor(Date.now() / 1000);
  const window_start = now - RATE_WINDOW_S;
  const global_bucket = `global:${Math.floor(now / RATE_WINDOW_S)}`;
  const machine_bucket = `machine:${machine_id}:${Math.floor(now / RATE_WINDOW_S)}`;

  // Prune old events, then record this attempt.
  await db
    .prepare('DELETE FROM rate_events WHERE ts < ?1')
    .bind(window_start)
    .run();
  await db
    .prepare('INSERT INTO rate_events (bucket, ts) VALUES (?1, ?2)')
    .bind(machine_bucket, now)
    .run();

  const per_machine = await count_events(db, machine_bucket, window_start);
  if (per_machine > RATE_LIMIT) return true;

  const global = await count_events(db, global_bucket, window_start);
  // Global cap is intentionally loose (abuse brake, not a per-user limit).
  return global > RATE_LIMIT * 200;
}

async function count_events(db, bucket, window_start) {
  const { results } = await db
    .prepare('SELECT COUNT(*) AS n FROM rate_events WHERE bucket = ?1 AND ts >= ?2')
    .bind(bucket, window_start)
    .all();
  return results?.[0]?.n ?? 0;
}

// ── Helpers ───────────────────────────────────────────────────────────────

async function read_json(request) {
  const raw = await request.text();
  if (raw.length > MAX_BODY_BYTES) {
    return { ok: false, error: 'request body too large' };
  }
  try {
    const value = JSON.parse(raw);
    if (!value || typeof value !== 'object' || Array.isArray(value)) {
      return { ok: false, error: 'invalid JSON body' };
    }
    return { ok: true, value };
  } catch {
    return { ok: false, error: 'invalid JSON body' };
  }
}

function str_field(v) {
  return typeof v === 'string' && v.length > 0 ? v : null;
}

function base64_decode(s) {
  const norm = s.replace(/-/g, '+').replace(/_/g, '/');
  const bin = atob(norm);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

function hex_decode(s) {
  if (!/^[0-9a-fA-F]+$/.test(s) || s.length % 2 !== 0) {
    throw new Error('bad hex');
  }
  const out = new Uint8Array(s.length / 2);
  for (let i = 0; i < out.length; i++) {
    out[i] = parseInt(s.slice(i * 2, i * 2 + 2), 16);
  }
  return out;
}

// Native WebCrypto Ed25519 verification (workerd supports Ed25519).
async function verify_ed25519(public_key, signature, data) {
  try {
    const key = await crypto.subtle.importKey(
      'raw',
      public_key,
      { name: 'Ed25519' },
      false,
      ['verify'],
    );
    return await crypto.subtle.verify(
      { name: 'Ed25519' },
      key,
      signature,
      data,
    );
  } catch {
    return false;
  }
}

function new_token() {
  const bytes = new Uint8Array(32);
  crypto.getRandomValues(bytes);
  let bin = '';
  for (const b of bytes) bin += String.fromCharCode(b);
  return btoa(bin).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

function timing_safe_equal(a, b) {
  let diff = a.length ^ b.length;
  for (let i = 0; i < a.length; i++) diff |= a.charCodeAt(i) ^ b.charCodeAt(i);
  return diff === 0;
}

function json_response(obj, status = 200, extra_headers = null) {
  const headers = {
    'content-type': 'application/json',
    'cache-control': 'no-store',
    'x-content-type-options': 'nosniff',
    'allow': 'GET, POST',
    ...(extra_headers ?? {}),
  };
  return new Response(JSON.stringify(obj), { status, headers });
}
